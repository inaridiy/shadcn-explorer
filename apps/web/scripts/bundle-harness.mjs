#!/usr/bin/env node
/**
 * preview-harness/ (node_modules と生成物を除く) を tar.gz にして、Worker から参照できる TS ファイルに書き出す。
 * フォールバックの Coding Agent のサンドボックスに同じハーネスを配るため (setup.sh で依存を入れて同じ状態にする)。
 * 再現性のため、ファイル名順・時刻固定で固める。
 */
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const harness = path.join(root, "preview-harness")
const out = path.join(root, "src/infrastructure/harness-bundle.gen.ts")

const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "."], { cwd: harness, encoding: "utf8" })
  .split("\n")
  .filter((f) => f && !f.startsWith("node_modules/") && !f.startsWith("dist/"))
  .sort()
const tar = execFileSync(
  "tar",
  ["--sort=name", "--mtime=2026-01-01 00:00Z", "--owner=0", "--group=0", "--numeric-owner", "-cf", "-", ...files],
  { cwd: harness, maxBuffer: 64 * 1024 * 1024 },
)
// -n: 名前と時刻を入れない (同じ中身なら同じバイト列)
const tgz = execFileSync("gzip", ["-n", "-9"], { input: tar, maxBuffer: 64 * 1024 * 1024 })
const base64 = tgz.toString("base64")
const hash = createHash("sha256").update(tgz).digest("hex").slice(0, 16)
const body = `// Generated by scripts/bundle-harness.mjs. Do not edit.\n// preview-harness/ (${files.length} files) as tar.gz, for the fallback agent's sandbox.\nexport const HARNESS_BUNDLE_HASH = ${JSON.stringify(hash)}\nexport const HARNESS_BUNDLE_BASE64 = ${JSON.stringify(base64)}\n`
let previous = ""
try {
  previous = readFileSync(out, "utf8")
} catch {}
if (previous !== body) writeFileSync(out, body)
// The container image carries the same hash, so the Worker can refuse to run on a container whose image has not been
// rolled out yet (image rollouts after a deploy are gradual). Ignored by git, so it is not part of the bundle itself.
writeFileSync(path.join(harness, ".harness-version"), `${hash}\n`)
console.log(`harness bundle: ${files.length} files, ${tgz.length} bytes (${hash})`)
